# 試験用の「架空の商品」。本物の商品名は手元に無い（班の DB は読まない約束）ので、10 カテゴリー・約 7,766 件を規則で作る。
# 件数と 10 カテゴリーは backend/db_schema.md のとおり。名前の種は docs/mock と frontend のテストにある言葉（ガーゼタオル、ハーブティー 5種セット、入浴剤 ギフト、ドライフルーツ ギフト、果肉入りのゼリー、カタログギフト）。
import random

ITEMS = {
    "食品": ["焼き菓子", "クッキー", "フィナンシェ", "バウムクーヘン", "マカロン", "チョコレート", "ゼリー", "果肉入りのゼリー", "プリン", "どら焼き", "羊羹", "せんべい", "ドライフルーツ", "はちみつ", "ジャム", "海苔", "佃煮", "ラスク", "カステラ", "和菓子", "おかき", "ケーキ", "ハム", "カレー", "そうめん"],
    "飲料": ["紅茶", "緑茶", "ハーブティー", "コーヒー", "ドリップコーヒー", "玄米茶", "ジュース", "炭酸水", "麦茶", "抹茶", "ほうじ茶", "ミネラルウォーター"],
    "生活雑貨": ["ガーゼタオル", "今治タオル", "タオルセット", "ハンカチ", "マグカップ", "箸", "ブランケット", "キャンドル", "フォトフレーム", "エコバッグ", "靴下", "ルームフレグランス", "湯呑み", "ふきん"],
    "フラワー": ["花束", "フラワーアレンジメント", "プリザーブドフラワー", "観葉植物", "ブーケ", "胡蝶蘭", "ドライフラワー", "バラ"],
    "コスメ": ["ハンドクリーム", "入浴剤", "バスソルト", "フェイスマスク", "リップクリーム", "ボディソープ", "アロマオイル", "ヘアオイル", "ボディミルク"],
    "酒類": ["赤ワイン", "白ワイン", "日本酒", "ビール", "ウイスキー", "梅酒", "シャンパン", "焼酎", "クラフトジン", "スパークリングワイン"],
    "インテリア": ["花瓶", "置き時計", "クッション", "アロマディフューザー", "ミラー", "ランプ", "コースター"],
    "家電": ["ドライヤー", "加湿器", "電気ケトル", "ミニ扇風機", "ワイヤレスイヤホン", "モバイルバッテリー", "ホットアイマスク"],
    "ビジネス小物": ["名刺入れ", "ボールペン", "ノート", "カードケース", "ペンケース", "万年筆", "ネームホルダー"],
    "カタログギフト": ["カタログギフト"],
}
# 件数の配分は db_schema.md の products.category の件数に比例（合計 7,766 に合わせる）
SHARE = {"生活雑貨": 1965, "食品": 1908, "コスメ": 853, "飲料": 792, "家電": 496, "インテリア": 464, "ビジネス小物": 420, "フラワー": 406, "酒類": 387, "カタログギフト": 309}
PREFIX = ["", "", "", "京都", "北海道", "静岡", "神戸", "銀座", "北欧風", "森の", "季節の", "国産", "無添加", "老舗の", "職人の"]
SUFFIX = ["", " ギフト", " セット", " 詰め合わせ", " ミニ", " 高級", " 人気", " プレミアム", " お試し", " 送料無料"]
COUNT = ["", "", "3個入り", "5種セット", "10個入り", "12本入り", "20包", "1箱", "2枚組"]


def build(n_total: int = 7766, seed: int = 11) -> list[dict]:
    rnd = random.Random(seed)
    scale = n_total / sum(SHARE.values())
    rows: list[dict] = []
    for cat, n in SHARE.items():
        for _ in range(round(n * scale)):
            base = rnd.choice(ITEMS[cat])
            name = " ".join(x for x in [rnd.choice(PREFIX), base + rnd.choice(SUFFIX), rnd.choice(COUNT)] if x).replace("  ", " ").strip()
            rows.append({"name": name, "category": cat, "base": base})
    # 入れ方の都合で連番を振る
    for i, r in enumerate(rows):
        r["product_id"] = f"S{i:05d}"
    return rows


if __name__ == "__main__":
    rs = build()
    print(len(rs))
    for r in rs[:8]:
        print(r)
